@dataclass
class GroundTruthEvent:
    label: str
    start: float
    end: float


def build_simulated_session(con_ruido_extra: float = 0.0) -> Tuple[np.ndarray, List[GroundTruthEvent]]:
    # Sesión sintética: normal -> corriendo -> caída -> auxilio -> normal.
    # con_ruido_extra > 0 añade ruido blanco para probar la mejora de audio.
    segments: List[np.ndarray] = []
    gt_events: List[GroundTruthEvent] = []
    cursor = 0.0

    def add_segment(audio_segment, label):
        nonlocal cursor
        dur = len(audio_segment) / SR
        segments.append(audio_segment)
        if label != "ruido_normal":
            gt_events.append(GroundTruthEvent(label, round(cursor, 2), round(cursor + dur, 2)))
        cursor += dur

    add_segment(generate_ambient_noise(3.0, amp=0.04) + generate_footstep_sequence(3.0, 1.8, amp=0.35), "ruido_normal")
    add_segment(generate_ambient_noise(2.5, amp=0.05) + generate_footstep_sequence(2.5, 4.2, amp=0.5), "corriendo")
    add_segment(generate_ambient_noise(0.6, amp=0.03), "ruido_normal")
    caida = overlay(generate_ambient_noise(1.0, amp=0.03), generate_impact(duration=0.3, amp=1.0), offset_sec=0.35)
    add_segment(caida, "caida")
    grito = overlay(generate_ambient_noise(1.6, amp=0.03), generate_scream(duration=1.0, amp=0.8, f0=520.0), offset_sec=0.3)
    add_segment(grito, "pedido_auxilio")
    add_segment(generate_ambient_noise(2.5, amp=0.04) + generate_footstep_sequence(2.5, 1.6, amp=0.3), "ruido_normal")

    full = np.concatenate(segments).astype(np.float32)
    if con_ruido_extra > 0:
        full = full + np.random.normal(0, con_ruido_extra, len(full)).astype(np.float32)
    full = full / (np.max(np.abs(full)) + 1e-9) * 0.9
    return full, gt_events


