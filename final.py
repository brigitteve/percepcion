"""## 3. Mejora de audio (reducción de ruido)

Tres pasos, en este orden:

1. **Filtro pasa-altos** Butterworth (orden 4, fase cero): quita el rumor grave que no aporta información.
2. **Spectral gating** (`noisereduce`, modo estacionario): estima el perfil de ruido a partir del tramo **más silencioso** del propio audio (no hace falta una muestra de ruido aparte) y atenúa lo que quede por debajo.
   Al ser estacionario, **conserva los transitorios cortos** (impactos y pisadas) y los gritos.
3. **Normalización de pico** a 0.9 para que los umbrales del clasificador trabajen en una escala comparable entre grabaciones.

Se muestra la relación señal-ruido estimada antes y después.
"""

def filtro_pasa_altos(y: np.ndarray, sr: int, corte_hz: float = CORTE_PASA_ALTOS_HZ) -> np.ndarray:
    sos = butter(4, corte_hz, btype="highpass", fs=sr, output="sos")
    return sosfiltfilt(sos, y).astype(np.float32)


def tramo_mas_silencioso(y: np.ndarray, sr: int, dur: float = 0.5) -> np.ndarray:
    # Devuelve la ventana de `dur` s con menor energía RMS: se usa como muestra de ruido de fondo.
    win = int(dur * sr)
    if len(y) <= win:
        return y
    hop = win // 2
    rms = [np.sqrt(np.mean(y[i:i + win] ** 2)) for i in range(0, len(y) - win, hop)]
    i = int(np.argmin(rms)) * hop
    return y[i:i + win]


def estimar_snr_db(y: np.ndarray, sr: int) -> float:
    # SNR aproximada: energía de los frames más fuertes (percentil 95) frente a los más débiles (percentil 10).
    rms = librosa.feature.rms(y=y)[0] + 1e-9
    return float(20 * np.log10(np.percentile(rms, 95) / np.percentile(rms, 10)))


def mejorar_audio(y: np.ndarray, sr: int = SR, fuerza: float = FUERZA_REDUCCION_RUIDO) -> np.ndarray:
    y = y - np.mean(y)                                   # quita componente continua
    y = filtro_pasa_altos(y, sr)
    ruido = tramo_mas_silencioso(y, sr)
    y = nr.reduce_noise(y=y, sr=sr, y_noise=ruido, stationary=True,
                        prop_decrease=fuerza, n_fft=1024)
    y = y.astype(np.float32)
    pico = np.max(np.abs(y)) + 1e-9
    return (y / pico * 0.9).astype(np.float32)


