"""## 8. Análisis de la sesión completa (ventana deslizante)

Ventana de 1.0 s con salto de 0.5 s; las ventanas consecutivas de la misma categoría se fusionan en un
único evento (`DetectedEvent`) con los campos de **RD-02**.
"""

@dataclass
class DetectedEvent:
    category: str
    risk_level: str
    confidence: float
    start: float
    end: float
    alarm_activated: bool
    stair_id: str = "Escalera-Principal"


def analyze_session(
    audio: np.ndarray,
    sr: int = SR,
    window_sec: float = 1.0,
    hop_sec: float = 0.5,
    sensitivity: str = "media",
    stair_id: str = "Escalera-Principal",
) -> Tuple[List[DetectedEvent], ClassificationThresholds]:
    thresholds = SensitivityConfig(sensitivity).apply(ClassificationThresholds())

    win = int(window_sec * sr)
    hop = int(hop_sec * sr)
    raw_windows = []

    t = 0
    while t + win <= len(audio):
        segment = audio[t : t + win]
        category, risk, confidence = classify_window(segment, sr, thresholds)
        raw_windows.append((t / sr, (t + win) / sr, category, risk, confidence))
        t += hop

    # Fusión de ventanas consecutivas de la misma categoría (se ignora "ruido_normal")
    merged = []
    current = None
    for start, end, category, risk, confidence in raw_windows:
        if category == "ruido_normal":
            if current:
                merged.append(current)
                current = None
            continue
        if current and current["category"] == category and start <= current["end"] + hop_sec + 1e-6:
            current["end"] = end
            current["confidence"] = max(current["confidence"], confidence)
        else:
            if current:
                merged.append(current)
            current = {"category": category, "risk": risk, "confidence": confidence, "start": start, "end": end}
    if current:
        merged.append(current)

    events = [
        DetectedEvent(
            category=m["category"],
            risk_level=m["risk"],
            confidence=round(m["confidence"], 2),
            start=round(m["start"], 2),
            end=round(m["end"], 2),
            alarm_activated=(m["risk"] == "alto"),
            stair_id=stair_id,
        )
        for m in merged
    ]
    return events, thresholds


