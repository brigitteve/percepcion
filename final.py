"""## 6. Extracción de características con `librosa`

| Función | Riesgo que soporta | Idea |
|---|---|---|
| `compute_footstep_rate` | 1. Persona corriendo | Cuenta *onsets* por segundo (cadencia de pisadas) |
| `compute_impact_score` | 2. Caída | Pico de energía RMS y *crest factor* (transitorio súbito) |
| `compute_fundamental_frequency` | 3. Pedido de auxilio | F0 mediana vía `librosa.pyin`, sólo en tramos con voz (*voiced*) |
"""

def compute_footstep_rate(segment: np.ndarray, sr: int = SR) -> Tuple[float, int]:
    #Devuelve (pasos_por_segundo, n_onsets) a partir de la envolvente de onsets.#
    if len(segment) < 512:
        return 0.0, 0
    onset_env = librosa.onset.onset_strength(y=segment, sr=sr)
    onsets = librosa.onset.onset_detect(onset_envelope=onset_env, sr=sr, backtrack=False)
    duration = len(segment) / sr
    if duration <= 0:
        return 0.0, 0
    return len(onsets) / duration, len(onsets)


def compute_impact_score(segment: np.ndarray, sr: int = SR) -> Tuple[float, float]:
    #Devuelve (pico_rms, crest_factor) para detectar transitorios de impacto.#
    if len(segment) < 1024:
        return 0.0, 0.0
    rms = librosa.feature.rms(y=segment)[0]
    peak_rms = float(rms.max())
    mean_rms = float(rms.mean()) + 1e-6
    crest_factor = peak_rms / mean_rms
    return peak_rms, crest_factor


def compute_fundamental_frequency(
    segment: np.ndarray, sr: int = SR, fmin: float = 150.0, fmax: float = 1100.0
) -> Tuple[float, float]:
    #Devuelve (f0_mediana_Hz, confianza_media) usando sólo tramos con voz detectada.#
    if len(segment) < sr * 0.2:  # muy corto para pyin
        return 0.0, 0.0
    try:
        f0, voiced_flag, voiced_prob = librosa.pyin(segment, fmin=fmin, fmax=fmax, sr=sr)
    except Exception:
        return 0.0, 0.0
    if f0 is None or not np.any(voiced_flag):
        return 0.0, 0.0
    f0_voiced = f0[voiced_flag]
    conf_voiced = voiced_prob[voiced_flag]
    f0_voiced = f0_voiced[~np.isnan(f0_voiced)]
    if len(f0_voiced) == 0:
        return 0.0, 0.0
    return float(np.median(f0_voiced)), float(np.mean(conf_voiced))


