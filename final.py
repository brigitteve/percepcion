def generate_footstep(duration=0.15, freq=90.0, sr=SR, amp=0.5):
    #Sintetiza una única pisada: un golpe grave con ruido y caída exponencial.
    t = np.linspace(0, duration, int(sr * duration), endpoint=False)
    tone = np.sin(2 * np.pi * freq * t)
    noise = np.random.normal(0, 0.3, len(t))
    env = np.exp(-t * 25)
    return amp * (tone * 0.6 + noise * 0.4) * env


def generate_footstep_sequence(total_duration, steps_per_second, sr=SR, amp=0.5, jitter=0.02):
    #Concatena pisadas a una cadencia dada (pasos/segundo), con jitter natural.
    audio = np.zeros(int(total_duration * sr))
    step_interval = 1.0 / steps_per_second
    t_cursor = 0.0
    while t_cursor < total_duration:
        jittered = max(t_cursor + np.random.uniform(-jitter, jitter), 0.0)
        idx = int(jittered * sr)
        step = generate_footstep(sr=sr, amp=amp * np.random.uniform(0.85, 1.15))
        end = min(idx + len(step), len(audio))
        if end > idx:
            audio[idx:end] += step[: end - idx]
        t_cursor += step_interval
    return audio


def generate_ambient_noise(duration, sr=SR, amp=0.05):
    #Ruido de fondo típico de una escalera (conversación lejana, aire, pasos difusos).#
    return np.random.normal(0, amp, int(duration * sr))


def generate_impact(duration=0.3, sr=SR, amp=1.0):
    #Sonido de impacto/golpe súbito característico de una caída.#
    n = int(duration * sr)
    t = np.linspace(0, duration, n, endpoint=False)
    noise = np.random.normal(0, 1, n)
    low_thump = np.sin(2 * np.pi * 60 * t)
    env = np.exp(-t * 15)  # ataque casi instantáneo, decaimiento rápido
    return amp * (noise * 0.5 + low_thump * 0.5) * env


def generate_scream(duration=1.0, sr=SR, amp=0.7, f0=550.0):
    #Grito/pedido de auxilio sintético con F0, armónicos y vibrato.#
    n = int(duration * sr)
    t = np.linspace(0, duration, n, endpoint=False)
    vibrato = 20 * np.sin(2 * np.pi * 6 * t)
    freq_track = f0 + vibrato + np.linspace(0, 80, n)  # leve glissando ascendente
    phase = 2 * np.pi * np.cumsum(freq_track) / sr
    fundamental = np.sin(phase)
    harmonic2 = 0.5 * np.sin(2 * phase)
    harmonic3 = 0.25 * np.sin(3 * phase)
    voice = fundamental + harmonic2 + harmonic3
    noise = np.random.normal(0, 0.15, n)

    attack = int(0.05 * sr)
    env = np.ones(n)
    env[:attack] = np.linspace(0, 1, attack)
    env[-attack:] = np.linspace(1, 0, attack)
    return amp * (voice * 0.85 + noise * 0.15) * env


def overlay(base: np.ndarray, sound: np.ndarray, offset_sec: float = 0.0, sr: int = SR) -> np.ndarray:
    #Suma 'sound' sobre 'base' a partir de offset_sec, recortando si es necesario.#
    start = int(offset_sec * sr)
    end = min(start + len(sound), len(base))
    if end > start:
        base[start:end] += sound[: end - start]
    return base


