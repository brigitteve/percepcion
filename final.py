"""## 7. Motor de clasificación (RF-02, RF-03, RF-07)

Clasificador base por umbrales con prioridad `impacto > grito > corriendo > normal`.
`SensitivityConfig` implementa el ajuste de sensibilidad de **RF-07**.

> Los umbrales vienen calibrados con audio sintético. Con grabaciones reales conviene ajustarlos
> (usa la sensibilidad `alta`/`baja` o edita `ClassificationThresholds`).
"""

@dataclass
class ClassificationThresholds:
    running_steps_per_sec: float = 3.0     # por encima de esto se considera "corriendo"
    scream_fmin: float = 250.0             # rango de F0 típico de un grito de auxilio
    scream_fmax: float = 900.0
    scream_min_confidence: float = 0.5     # confianza mínima de voz (voiced_prob) de pyin
    impact_rms_threshold: float = 0.15     # pico de energía mínimo para considerar impacto
    impact_crest_factor: float = 4.0       # qué tan "puntiagudo" debe ser el transitorio


class SensitivityConfig:
    #Ajuste global de sensibilidad de detección (RF-07).#

    _SCALES = {"baja": 1.3, "media": 1.0, "alta": 0.75}

    def __init__(self, level: str = "media"):
        if level not in self._SCALES:
            raise ValueError(f"Nivel de sensibilidad inválido: {level!r}")
        self.level = level
        self.scale = self._SCALES[level]

    def apply(self, base: ClassificationThresholds) -> ClassificationThresholds:
        adjusted = ClassificationThresholds(**asdict(base))
        adjusted.running_steps_per_sec *= self.scale
        adjusted.impact_rms_threshold *= self.scale
        adjusted.impact_crest_factor *= self.scale
        adjusted.scream_min_confidence = min(0.95, adjusted.scream_min_confidence * self.scale)
        return adjusted


def classify_window(
    segment: np.ndarray, sr: int, thresholds: ClassificationThresholds
) -> Tuple[str, str, float]:
    #Clasifica una ventana de audio y devuelve (categoria, nivel_riesgo, confianza).#
    step_rate, _ = compute_footstep_rate(segment, sr)
    peak_rms, crest = compute_impact_score(segment, sr)
    f0_median, f0_conf = compute_fundamental_frequency(
        segment, sr, fmin=thresholds.scream_fmin - 50, fmax=thresholds.scream_fmax + 100
    )

    # 1) Impacto / caída -> riesgo alto (máxima prioridad, RF-03)
    if peak_rms >= thresholds.impact_rms_threshold and crest >= thresholds.impact_crest_factor:
        confidence = min(
            1.0,
            0.5 * (peak_rms / thresholds.impact_rms_threshold)
            + 0.5 * (crest / thresholds.impact_crest_factor),
        )
        return "caida", "alto", round(confidence, 2)

    # 2) Pedido de auxilio -> riesgo alto
    if (
        thresholds.scream_fmin <= f0_median <= thresholds.scream_fmax
        and f0_conf >= thresholds.scream_min_confidence
    ):
        return "pedido_auxilio", "alto", round(min(1.0, f0_conf), 2)

    # 3) Persona corriendo -> riesgo medio
    if step_rate >= thresholds.running_steps_per_sec:
        confidence = min(1.0, step_rate / (thresholds.running_steps_per_sec * 1.5))
        return "corriendo", "medio", round(confidence, 2)

    # 4) Ruido normal -> riesgo bajo
    normal_confidence = 1.0 - min(step_rate / max(thresholds.running_steps_per_sec, 1e-6), 1.0) * 0.3
    return "ruido_normal", "bajo", round(max(0.0, normal_confidence), 2)


